-- --- 2) รายงานก่อนแก้ -----------------------------------------
select 'ก่อนแก้' as phase, jsonb_pretty(jsonb_build_object(
  'จากไฟล์',         (select count(*) from njhr_emptype_src),
  'จับคู่รหัสได้',    (select count(*) from njhr_emptype_src s
                         join public.employees e on upper(btrim(e.emp_code)) = upper(btrim(s.emp_code))),
  'ไม่พบรหัสในระบบ', coalesce((select jsonb_agg(s.emp_code order by s.emp_code)
                         from njhr_emptype_src s
                        where not exists (select 1 from public.employees e
                                           where upper(btrim(e.emp_code)) = upper(btrim(s.emp_code)))), '[]'::jsonb),
  'ค่าที่จะเขียน',    (select jsonb_object_agg(t, n) from
                         (select emp_type t, count(*) n from njhr_emptype_src group by emp_type) x)
)) as report;


-- --- 3) UPDATE เฉพาะ emp_type ---------------------------------
update public.employees e
   set emp_type = btrim(s.emp_type)
  from njhr_emptype_src s
 where upper(btrim(e.emp_code)) = upper(btrim(s.emp_code))
   and coalesce(btrim(e.emp_type),'') is distinct from btrim(s.emp_type);


-- --- 4) รายงานหลังแก้ -----------------------------------------
select 'หลังแก้' as phase, jsonb_pretty(jsonb_build_object(
  'พนักงานทั้งหมด',  (select count(*) from public.employees),
  'มีประเภทแล้ว',    (select count(*) from public.employees
                         where coalesce(btrim(emp_type),'') <> ''),
  'ยังว่าง',         (select count(*) from public.employees
                         where coalesce(btrim(emp_type),'') = ''),
  'แยกตามประเภท',   coalesce((select jsonb_object_agg(t, n) from
                         (select coalesce(nullif(btrim(emp_type),''),'(ว่าง)') t, count(*) n
                            from public.employees group by 1) x), '{}'::jsonb),
  'ตัวอย่าง 5 คน',   (select jsonb_agg(jsonb_build_object('code', y.emp_code, 'type', y.emp_type))
                         from (select emp_code, emp_type from public.employees
                                order by emp_code limit 5) y),
  'รหัสที่ยังว่าง',  coalesce((select jsonb_agg(emp_code order by emp_code)
                         from public.employees where coalesce(btrim(emp_type),'') = ''), '[]'::jsonb)
)) as report;
