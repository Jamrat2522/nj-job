-- --- 0) PREFLIGHT --------------------------------------------
do $$
declare v_type text;
begin
  select data_type into v_type from information_schema.columns
   where table_schema='public' and table_name='employees' and column_name='emp_type';
  if v_type is null then
    raise exception 'PREFLIGHT: ไม่พบคอลัมน์ employees.emp_type';
  end if;
  if v_type <> 'text' then
    raise exception 'PREFLIGHT: employees.emp_type ไม่ใช่ text แต่เป็น % - หยุดก่อน ส่งค่ากลับมา', v_type;
  end if;
  raise notice 'ก่อนซ่อม: มีค่า % คน / ว่าง % คน จากทั้งหมด % คน',
    (select count(*) from public.employees where coalesce(btrim(emp_type),'') <> ''),
    (select count(*) from public.employees where coalesce(btrim(emp_type),'') = ''),
    (select count(*) from public.employees);
end $$;


